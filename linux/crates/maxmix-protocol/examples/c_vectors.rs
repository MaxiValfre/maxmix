//! Emit a C header of cross-language conformance vectors for the firmware.
//!
//! Run: `cargo run -q -p maxmix-protocol --example c_vectors > ../firmware/test/vectors.h`
//! The firmware's portable C protocol core is tested against these bytes, so the
//! Rust host and the C firmware provably agree on the wire format.

use maxmix_protocol::{
    DeviceToHost, HostToDevice, LightingConfig, LightingMode, Rgb, SessionInfo, SessionSlot,
    VolumeData,
};

fn arr(name: &str, bytes: &[u8]) {
    let body: Vec<String> = bytes.iter().map(|b| format!("0x{b:02X}")).collect();
    println!("static const uint8_t {name}[] = {{{}}};", body.join(", "));
}

fn main() {
    println!("/* AUTO-GENERATED by linux/crates/maxmix-protocol/examples/c_vectors.rs. Do not edit. */");
    println!("#ifndef MAXMIX_VECTORS_H\n#define MAXMIX_VECTORS_H\n#include <stdint.h>\n");

    // Host -> Device: the firmware must decode these.
    arr("V_HELLO", &HostToDevice::Hello { proto_version: 2 }.encode());
    arr("V_PING", &HostToDevice::Ping.encode());
    arr(
        "V_SESSION_INFO",
        &HostToDevice::SessionInfo(SessionInfo { mode: 2, current: 1, count: 3 }).encode(),
    );
    arr(
        "V_SESSION_DATA",
        &HostToDevice::SessionData {
            slot: SessionSlot::Current,
            volume: VolumeData { id: 19, is_default: false, volume: 75, is_muted: true },
            name: "Café Spotify".into(),
        }
        .encode(),
    );
    arr(
        "V_VOLUME_SET",
        &HostToDevice::VolumeSet {
            slot: SessionSlot::Next,
            volume: VolumeData { id: 5, is_default: true, volume: 100, is_muted: false },
        }
        .encode(),
    );
    arr(
        "V_LIGHTING",
        &HostToDevice::Lighting(LightingConfig {
            mode: LightingMode::Pulse,
            speed: 7,
            color_min: Rgb::new(0, 0, 32),
            color_max: Rgb::new(0, 128, 255),
            idle_mode: LightingMode::Fade,
            idle_timeout_s: 30,
            volume_min: Rgb::new(0, 255, 64),
            volume_max: Rgb::new(255, 0, 0),
        })
        .encode(),
    );
    arr(
        "V_DEVICE_CONFIG",
        &HostToDevice::DeviceConfig {
            acceleration: 60,
            sleep_after_s: 10,
            continuous_scroll: true,
            ring_reversed: true,
            dim_after_s: 20,
        }
        .encode(),
    );

    // Device -> Host: the firmware's encoder must produce exactly these bytes.
    arr("V_HELLO_ACK", &DeviceToHost::HelloAck { fw_major: 2, fw_minor: 0, capabilities: 1 }.encode());
    arr("V_PONG", &DeviceToHost::Pong.encode());
    arr(
        "V_VOLUME_CHANGE",
        &DeviceToHost::VolumeChange {
            slot: SessionSlot::Current,
            volume: VolumeData { id: 19, is_default: false, volume: 42, is_muted: true },
        }
        .encode(),
    );
    arr("V_SESSION_REQUEST", &DeviceToHost::SessionRequest { direction: 1 }.encode());
    arr("V_BUTTON", &DeviceToHost::Button { event: 2 }.encode());

    // A noisy stream: garbage, a frame with a smashed CRC, then a valid PING.
    let mut noisy = vec![0x00, 0xFF, 0xA5, 0xFF];
    let mut bad = HostToDevice::SessionInfo(SessionInfo { mode: 2, current: 0, count: 1 }).encode();
    let last = bad.len() - 1;
    bad[last] ^= 0xFF;
    noisy.extend(bad);
    noisy.extend(HostToDevice::Ping.encode());
    arr("V_NOISY_THEN_PING", &noisy);

    println!("\n#endif");
}
